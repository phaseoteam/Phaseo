#!/usr/bin/env node
// Turn src/generated/relationships.json into src/generated/relationships.ts.
//
//   node packages/data/db/scripts/build-relationships-module.mjs
//
// Run after generate-relationships.mjs. The JSON stays the readable, diffable copy; apps import the .ts.
// Why: bundlers re-print an imported JSON file as a JS object literal (~550 KiB in the gateway Worker for
// ~280 KiB of data), and V8 builds that object at load whether or not PlanetScale is selected. A single
// string literal is cheap to load, and JSON.parse runs only when a client first needs the metadata.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = join(dirname(fileURLToPath(import.meta.url)), "../src/generated");
const metadata = JSON.parse(readFileSync(join(dir, "relationships.json"), "utf8"));
const compact = JSON.stringify(metadata);

/** Single-quoted JS string literal: the JSON's double quotes need no escaping (JSON.stringify would add ~17%). */
function singleQuoted(text) {
	let out = "'";
	for (const ch of text) {
		const code = ch.charCodeAt(0);
		if (ch === "\\") out += "\\\\";
		else if (ch === "'") out += "\\'";
		else if (code === 0x2028 || code === 0x2029 || code < 0x20) out += `\\u${code.toString(16).padStart(4, "0")}`;
		else out += ch;
	}
	return `${out}'`;
}

const source = `// Generated by scripts/build-relationships-module.mjs from relationships.json. Do not edit.
import type { RelationshipMetadata } from "../relationships";

// One string literal, parsed on first use (see the script for why this is not a JSON import).
const RAW = ${singleQuoted(compact)};

let parsed: RelationshipMetadata | undefined;

export function loadRelationships(): RelationshipMetadata {
	parsed ??= JSON.parse(RAW) as RelationshipMetadata;
	return parsed;
}
`;
writeFileSync(join(dir, "relationships.ts"), source);
console.error(`relationships.ts: ${(compact.length / 1024).toFixed(0)} KiB of JSON`);
