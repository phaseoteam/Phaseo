// Purpose: Coverage accounting and the Markdown summary for the all-routes pricing sweep.
// Why: A sweep is only useful if it says what it covered, what it found and what it could not check.
// How: Counts routes, cards, rules, meters, condition branches, plans and time windows exercised by the expected
//      bills; groups mismatches by kind and provider; ranks money impact per 1M tokens or per request.

import type { Mismatch } from "../src/expect/types";
import { isTokenMeter } from "./cases";

export type CardCoverage = {
	key: string;
	provider: string;
	capability: string;
	rules: number;
	rulesExercised: Set<string>;
	/** plan|meter → exercised */
	meters: Map<string, boolean>;
	/** plan|meter|match → exercised */
	branches: Map<string, boolean>;
	/** plan → exercised */
	plans: Map<string, boolean>;
	/** rule|window label → exercised */
	windows: Map<string, boolean>;
	unreachable: Array<{ ruleId: string; reason: string }>;
	cases: number;
	casesByKind: Record<string, number>;
};

export type SweepTotals = {
	routes: number;
	routesByCapability: Record<string, { active: number; withCard: number; withCurrentRules: number }>;
	noCard: string[];
	noCurrentRules: string[];
	cards: CardCoverage[];
	documented: { cases: number; overNanos: number; underNanos: number; errorNanos: number; errors: number; over: number; under: number };
	calculatorErrors: string[];
	engineErrors: Record<string, number>;
	durationMs: number;
	now: string;
	/** How the catalogue rows were read (database role). */
	source: string;
};

function pct(part: number, whole: number): string {
	return whole ? `${((100 * part) / whole).toFixed(1)}%` : "n/a";
}

function usd(nanos: number): string {
	const sign = nanos < 0 ? "-" : "";
	return `${sign}$${(Math.abs(nanos) / 1e9).toFixed(Math.abs(nanos) < 1e7 ? 6 : 4)}`;
}

export type Impact = { mismatch: Mismatch; perUnitUsd: number; unit: string };

/**
 * Money impact normalised to 1M tokens of the meter at fault (that meter's own gap divided by its quantity), or per
 * request for non-token meters and errors.
 */
export function impactOf(mismatch: Mismatch): Impact | null {
	const nanos = mismatch.delta?.nanos;
	if (typeof nanos !== "number" || !nanos) return null;
	const meter = mismatch.delta?.meter;
	if (meter && isTokenMeter(meter) && mismatch.kind !== "wrong_value") {
		const expectedLines: any[] = (mismatch.expected as any)?.lines ?? [];
		const actualLines: any[] = (mismatch.actual as any)?.lines ?? [];
		const expectedNanos = expectedLines.filter((l) => (l[1] ?? l[0]) === meter).reduce((s, l) => s + Number(l[4]), 0);
		const expectedQty = expectedLines.filter((l) => (l[1] ?? l[0]) === meter).reduce((s, l) => s + Number(l[3]), 0);
		const actualNanos = actualLines.filter((l) => l[0] === meter).reduce((s, l) => s + Number(l[3]), 0);
		const actualQty = actualLines.filter((l) => l[0] === meter).reduce((s, l) => s + Number(l[1]), 0);
		const qty = expectedQty || actualQty || Math.abs(mismatch.delta?.tokens ?? 0);
		if (qty > 0) return { mismatch, perUnitUsd: ((actualNanos - expectedNanos) / qty) * 1e6 / 1e9, unit: `per 1M ${meter}` };
	}
	return { mismatch, perUnitUsd: nanos / 1e9, unit: "per request" };
}

export function coverageNumbers(totals: SweepTotals) {
	let rules = 0, rulesExercised = 0, meters = 0, metersExercised = 0, branches = 0, branchesExercised = 0, plans = 0, plansExercised = 0, windows = 0, windowsExercised = 0, cases = 0;
	const byMeter = new Map<string, { present: number; exercised: number }>();
	for (const card of totals.cards) {
		rules += card.rules;
		rulesExercised += card.rulesExercised.size;
		cases += card.cases;
		for (const [key, done] of card.meters) {
			meters += 1;
			if (done) metersExercised += 1;
			const meter = key.split("|")[1];
			const entry = byMeter.get(meter) ?? { present: 0, exercised: 0 };
			entry.present += 1;
			if (done) entry.exercised += 1;
			byMeter.set(meter, entry);
		}
		for (const done of card.branches.values()) { branches += 1; if (done) branchesExercised += 1; }
		for (const done of card.plans.values()) { plans += 1; if (done) plansExercised += 1; }
		for (const done of card.windows.values()) { windows += 1; if (done) windowsExercised += 1; }
	}
	return { rules, rulesExercised, meters, metersExercised, branches, branchesExercised, plans, plansExercised, windows, windowsExercised, cases, byMeter };
}

export function renderSummary(totals: SweepTotals, mismatches: Mismatch[]): string {
	const c = coverageNumbers(totals);
	const capRows = Object.entries(totals.routesByCapability).sort((a, b) => b[1].active - a[1].active);
	const activeWithCard = capRows.reduce((s, [, v]) => s + v.withCard, 0);
	const activeWithRules = capRows.reduce((s, [, v]) => s + v.withCurrentRules, 0);
	const lines: string[] = [];
	lines.push("# Pricing sweep summary", "");
	lines.push(`Generated by \`tools/provider-simulator/pricing/pricing.sim.ts\` from the catalogue database (${totals.source}). Clock ${totals.now}. Run time ${(totals.durationMs / 1000).toFixed(1)} s.`, "");
	lines.push("Expected costs come from `pricing/calculator.ts` (independent of the engine); actual costs from the gateway's `calculatePricing`. Cards are shaped like the request-context RPC (see `pricing/catalogue-cards.ts`).", "");

	lines.push("## Coverage", "");
	lines.push("| Measure | Covered | Present | Share |", "|---|---:|---:|---:|");
	lines.push(`| Active routes with a price card | ${activeWithCard} | ${totals.routes} | ${pct(activeWithCard, totals.routes)} |`);
	lines.push(`| Active routes with a rule in effect | ${activeWithRules} | ${totals.routes} | ${pct(activeWithRules, totals.routes)} |`);
	lines.push(`| Cards exercised | ${totals.cards.filter((card) => card.cases > 0).length} | ${totals.cards.length} | ${pct(totals.cards.filter((card) => card.cases > 0).length, totals.cards.length)} |`);
	lines.push(`| Rules exercised | ${c.rulesExercised} | ${c.rules} | ${pct(c.rulesExercised, c.rules)} |`);
	lines.push(`| Meters (card × plan × meter) exercised | ${c.metersExercised} | ${c.meters} | ${pct(c.metersExercised, c.meters)} |`);
	lines.push(`| Condition branches exercised | ${c.branchesExercised} | ${c.branches} | ${pct(c.branchesExercised, c.branches)} |`);
	lines.push(`| Plans (card × plan) exercised | ${c.plansExercised} | ${c.plans} | ${pct(c.plansExercised, c.plans)} |`);
	lines.push(`| Time windows exercised | ${c.windowsExercised} | ${c.windows} | ${pct(c.windowsExercised, c.windows)} |`);
	lines.push(`| Cases run | ${c.cases} | | |`, "");

	lines.push("### By capability", "", "| Capability | Active routes | With card | With current rules |", "|---|---:|---:|---:|");
	for (const [cap, v] of capRows) lines.push(`| ${cap} | ${v.active} | ${v.withCard} | ${v.withCurrentRules} |`);
	lines.push("");

	lines.push("### By meter", "", "| Meter | Exercised | Present |", "|---|---:|---:|");
	for (const [meter, v] of [...c.byMeter.entries()].sort((a, b) => b[1].present - a[1].present)) lines.push(`| ${meter} | ${v.exercised} | ${v.present} |`);
	lines.push("");

	const byKind = new Map<string, number>();
	const byProvider = new Map<string, Map<string, number>>();
	for (const m of mismatches) {
		byKind.set(m.kind, (byKind.get(m.kind) ?? 0) + 1);
		const p = byProvider.get(m.provider) ?? new Map<string, number>();
		const bucket = m.caseId.startsWith("catalogue:") ? "catalogue" : m.kind;
		p.set(bucket, (p.get(bucket) ?? 0) + 1);
		byProvider.set(m.provider, p);
	}
	lines.push("## Mismatches", "");
	lines.push(`${mismatches.length} in total (${mismatches.filter((m) => m.caseId.startsWith("catalogue:")).length} catalogue data checks, the rest engine vs expected).`, "");
	lines.push("| Kind | Count |", "|---|---:|");
	for (const [kind, n] of [...byKind.entries()].sort((a, b) => b[1] - a[1])) lines.push(`| ${kind} | ${n} |`);
	lines.push("");
	const cols = ["billing_over", "billing_under", "wrong_value", "invented", "dropped", "catalogue"];
	lines.push("### By provider", "", `| Provider | ${cols.join(" | ")} |`, `|---|${cols.map(() => "---:").join("|")}|`);
	for (const [provider, counts] of [...byProvider.entries()].sort((a, b) => [...b[1].values()].reduce((x, y) => x + y, 0) - [...a[1].values()].reduce((x, y) => x + y, 0))) {
		lines.push(`| ${provider} | ${cols.map((col) => counts.get(col) ?? 0).join(" | ")} |`);
	}
	lines.push("");

	const errors = new Map<string, number>();
	for (const m of mismatches) if (m.path === "billing.error") {
		const key = String(m.actual).replace(/:[\w,]+$/, (s) => s.length > 60 ? ":…" : s);
		errors.set(key, (errors.get(key) ?? 0) + 1);
	}
	if (errors.size) {
		lines.push("### Engine errors", "", "| Error | Cases |", "|---|---:|");
		for (const [error, n] of [...errors.entries()].sort((a, b) => b[1] - a[1])) lines.push(`| \`${error}\` | ${n} |`);
		lines.push("");
	}

	const d = totals.documented;
	lines.push("## Documented-usage cases", "");
	lines.push(`${d.cases} cases (one typical response per route; text routes use the gateway IR usage through \`normalizeTextUsageForPricing\`).`, "");
	lines.push("| | Cases | Total |", "|---|---:|---:|");
	lines.push(`| Over-billed | ${d.over} | ${usd(d.overNanos)} |`);
	lines.push(`| Under-billed | ${d.under} | ${usd(d.underNanos)} |`);
	lines.push(`| Pricing threw (expected charge lost) | ${d.errors} | ${usd(d.errorNanos)} |`, "");

	const impacts = mismatches.filter((m) => !m.caseId.startsWith("catalogue:") && (m.kind === "billing_over" || m.kind === "billing_under" || m.path === "billing.error"))
		.map(impactOf).filter((x): x is Impact => Boolean(x));
	const top = (filter: (i: Impact) => boolean) => {
		const seen = new Set<string>();
		return impacts.filter(filter).sort((a, b) => Math.abs(b.perUnitUsd) - Math.abs(a.perUnitUsd)).filter((i) => {
			const key = `${i.mismatch.provider}|${i.mismatch.model}|${i.mismatch.delta?.meter}|${i.mismatch.kind}`;
			if (seen.has(key)) return false;
			seen.add(key);
			return true;
		}).slice(0, 10);
	};
	const table = (title: string, rows: Impact[]) => {
		lines.push(`### ${title}`, "", "| Provider | Model | Case | Kind | Meter | Delta |", "|---|---|---|---|---|---:|");
		for (const i of rows) lines.push(`| ${i.mismatch.provider} | ${i.mismatch.model} | ${i.mismatch.caseId} | ${i.mismatch.kind} | ${i.mismatch.delta?.meter ?? ""} | ${i.perUnitUsd >= 0 ? "+" : ""}$${i.perUnitUsd.toFixed(4)} ${i.unit} |`);
		lines.push("");
	};
	lines.push("## Largest money impact", "");
	table("Per 1M tokens of the meter at fault", top((i) => i.unit.startsWith("per 1M")));
	table("Per request (non-token meters and thrown errors)", top((i) => i.unit === "per request"));

	lines.push("## Not covered", "");
	const unreachable = totals.cards.flatMap((card) => card.unreachable.map((u) => `${card.key} ${u.ruleId}: ${u.reason}`));
	lines.push(`- ${totals.noCard.length} active routes have no price card (reported as \`catalogue:no-card\`): ${totals.noCard.slice(0, 12).join(", ")}${totals.noCard.length > 12 ? ", …" : ""}.`);
	lines.push(`- ${totals.noCurrentRules.length} active routes have a card with no rule in effect at the sweep clock (reported as \`catalogue:no-current-rules\`): ${totals.noCurrentRules.slice(0, 12).join(", ")}${totals.noCurrentRules.length > 12 ? ", …" : ""}.`);
	lines.push(`- ${unreachable.length} rules cannot be reached by a request (a provider SKU label next to standard rules, or a condition the solver cannot satisfy). First ones: ${unreachable.slice(0, 8).join("; ") || "none"}.`);
	if (totals.calculatorErrors.length) lines.push(`- ${totals.calculatorErrors.length} cases where the oracle could not price a rule: ${totals.calculatorErrors.slice(0, 5).join("; ")}.`);
	lines.push("- Condition values for media cards (image_params, video_params, resolution, mode, …) are handed to the engine in `usage.context`; media adapters build them from the request instead, so adapter-side extraction is not tested here.");
	lines.push("- Executor usage mapping is not exercised: documented cases start from the gateway IR usage (`core/ir.ts`), which the executor layer of the simulator covers.");
	lines.push("- BYOK fees, data-contribution discounts, tier markup and credits are applied after `calculatePricing` and are out of scope.");
	lines.push("- Catalogue rows are read from the database at run time, so results follow catalogue edits; compare runs by their clock.");
	lines.push("");
	return `${lines.join("\n")}\n`;
}

/** Shared limitations, also listed under "Not covered" in SUMMARY.md. */
export const GENERAL_LIMITS: Array<{ what: string; reason: string }> = [
	{ what: "adapter-side condition extraction for media cards", reason: "condition values (image_params, video_params, resolution, mode, ...) are handed to the engine in usage.context; media adapters derive them from the request, which this layer does not run" },
	{ what: "executor usage mapping", reason: "documented cases start from the gateway IR usage (core/ir.ts); the executor layer of the simulator covers native-to-IR mapping" },
	{ what: "BYOK fees, data-contribution discounts, tier markup, credits", reason: "applied after calculatePricing" },
	{ what: "SKUs that are not active (draft, deprecated, disabled)", reason: "the sweep prices active SKUs only, as the gateway does" },
];

/** Machine-readable coverage for the cross-layer report (results/pricing/coverage.json). */
export function coverageJson(totals: SweepTotals) {
	const byCapability: Record<string, { cards: number; cardsExercised: number; metersPresent: number; metersExercised: number }> = {};
	for (const [capability, v] of Object.entries(totals.routesByCapability)) {
		byCapability[capability] = { cards: v.withCard, cardsExercised: 0, metersPresent: 0, metersExercised: 0 };
	}
	for (const card of totals.cards) {
		const entry = (byCapability[card.capability] ??= { cards: 0, cardsExercised: 0, metersPresent: 0, metersExercised: 0 });
		if (card.cases > 0) entry.cardsExercised += 1;
		for (const done of card.meters.values()) {
			entry.metersPresent += 1;
			if (done) entry.metersExercised += 1;
		}
	}
	const c = coverageNumbers(totals);
	const activeRoutesWithCard = Object.values(totals.routesByCapability).reduce((sum, v) => sum + v.withCard, 0);
	return {
		activeRoutes: totals.routes,
		activeRoutesWithCard,
		cards: activeRoutesWithCard,
		cardsExercised: totals.cards.filter((card) => card.cases > 0).length,
		metersPresent: c.meters,
		metersExercised: c.metersExercised,
		conditionBranchesPresent: c.branches,
		conditionBranchesExercised: c.branchesExercised,
		byCapability: Object.fromEntries(Object.entries(byCapability).sort((a, b) => a[0].localeCompare(b[0]))),
		notCovered: [
			...totals.noCard.map((key) => ({ what: `route ${key}`, reason: "active route with no price card" })),
			...totals.noCurrentRules.map((key) => ({ what: `card ${key}`, reason: "no rule in effect at the sweep clock (all expired or not yet effective)" })),
			...totals.cards.flatMap((card) => card.unreachable.map((u) => ({ what: `rule ${card.key} ${u.ruleId}`, reason: u.reason }))),
			...totals.calculatorErrors.map((error) => ({ what: `case ${error.split(":")[0]}`, reason: `oracle could not price it: ${error}` })),
			...GENERAL_LIMITS,
		],
	};
}
