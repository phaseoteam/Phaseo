// Writes src/features/desktops/terminal/terminalPage.generated.ts: one HTML page with xterm.js, its fit add-on, its CSS
// and scripts/terminal-page/bridge.js inlined, so the terminal's WebView loads nothing from the network.
// Run after changing @xterm/xterm, @xterm/addon-fit or the bridge; `--check` fails when the file is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const read = (file) => readFileSync(file, "utf8").replace(/\r\n/g, "\n");
const packageFile = (name, file) => path.join(path.dirname(require.resolve(`${name}/package.json`)), file);
const version = (name) => JSON.parse(read(packageFile(name, "package.json"))).version;
// Inline scripts end at the first "</script", so any inside the code is escaped.
const script = (code) => `<script>${code.replace(/<\/script/gi, "<\\/script")}</script>`;

export function terminalPage() {
  const html = [
    "<!doctype html><html><head><meta charset=\"utf-8\">",
    "<meta name=\"viewport\" content=\"width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no\">",
    `<style>${read(packageFile("@xterm/xterm", "css/xterm.css"))}`,
    "html,body{margin:0;height:100%;overflow:hidden}#terminal{position:absolute;top:4px;right:6px;bottom:4px;left:8px}</style>",
    "</head><body><div id=\"terminal\"></div>",
    script(read(packageFile("@xterm/xterm", "lib/xterm.js"))),
    script(read(packageFile("@xterm/addon-fit", "lib/addon-fit.js"))),
    script(read(path.join(here, "terminal-page", "bridge.js"))),
    "</body></html>",
  ].join("\n");
  return [
    "// Generated by scripts/terminal-page.mjs (pnpm --filter @phaseo/mobile terminal-page). Do not edit.",
    `// @xterm/xterm ${version("@xterm/xterm")}, @xterm/addon-fit ${version("@xterm/addon-fit")}.`,
    `export const terminalPage = ${JSON.stringify(html)};`,
    "",
  ].join("\n");
}

const target = path.join(here, "..", "src", "features", "desktops", "terminal", "terminalPage.generated.ts");
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const page = terminalPage();
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = read(target); } catch { /* Missing counts as out of date. */ }
    if (current !== page) { console.error("terminalPage.generated.ts is out of date. Run pnpm --filter @phaseo/mobile terminal-page."); process.exit(1); }
    console.log("terminalPage.generated.ts is up to date.");
  } else {
    writeFileSync(target, page);
    console.log(`Wrote ${path.relative(process.cwd(), target)} (${Math.round(page.length / 1024)} KB).`);
  }
}
