// sync-sequences: pure planning tests plus an end-to-end run between two
// databases on a throwaway PostgreSQL 17 (see lib/test-cluster.mjs).
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { connect } from './lib/common.mjs';
import { testCluster } from './lib/test-cluster.mjs';
import { planSync } from './sync-sequences.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const script = path.join(here, 'sync-sequences.mjs');

const seq = (key, lastValue, extra = {}) => {
  const [schema, name] = key.split('.');
  return { schema, name, key, lastValue: lastValue === null ? null : BigInt(lastValue), incrementBy: 1n, minValue: 1n, maxValue: 9223372036854775807n, readable: true, ...extra };
};

describe('planSync', () => {
  it('sets source + margin, skips unused, never moves backwards, flags missing/extra/unreadable', () => {
    const plan = planSync(
      [seq('public.a', 100), seq('public.b', null), seq('public.c', 5), seq('public.d', 7), seq('public.e', 9, { readable: false })],
      [seq('public.a', null), seq('public.b', null), seq('public.c', 999_999), seq('public.e', 1), seq('public.z', 3)],
      { margin: 1000n },
    );
    const by = Object.fromEntries(plan.map((p) => [p.key, p]));
    expect(by['public.a']).toMatchObject({ action: 'set', desired: 1100n });
    expect(by['public.b'].action).toBe('skip-unused');
    expect(by['public.c'].action).toBe('skip-ahead');
    expect(by['public.d'].action).toBe('missing');
    expect(by['public.e'].action).toBe('unreadable');
    expect(by['public.z'].action).toBe('extra');
  });

  it('handles bigint values beyond Number.MAX_SAFE_INTEGER', () => {
    const big = '9007199254740993';
    const [p] = planSync([seq('public.big', big)], [seq('public.big', 1)], { margin: 10n });
    expect(p.desired).toBe(9007199254741003n);
  });

  it('clamps to the target max, and reports overflow when the source is already past it', () => {
    const max = { maxValue: 2147483647n };
    const [clamped] = planSync([seq('public.i', 2147483000)], [seq('public.i', 1, max)], { margin: 10_000n });
    expect(clamped).toMatchObject({ action: 'set', desired: 2147483647n });
    const [overflow] = planSync([seq('public.i', 2147483647)], [seq('public.i', 1, max)], { margin: 10_000n });
    expect(overflow.action).toBe('overflow');
  });

  it('descending sequences move down', () => {
    const desc = { incrementBy: -1n, minValue: -1000000n, maxValue: -1n };
    const [p] = planSync([seq('public.down', -50, desc)], [seq('public.down', null, desc)], { margin: 100n });
    expect(p).toMatchObject({ action: 'set', desired: -150n });
  });
});

const cluster = testCluster('sequences', 55462);
const SRC = 'ps_cutover_test_seq_src';
const TGT = 'ps_cutover_test_seq_tgt';

describe.skipIf(!cluster.available)(`sync-sequences end to end (${cluster.reason})`, () => {
  let srcUrl;
  let tgtUrl;
  const schema = `
    create schema private;
    create table public.t (id bigserial primary key, v text);
    create table private.ident (id int generated by default as identity primary key);
    create sequence public.unused_seq;
    create sequence public.only_source;
  `;

  beforeAll(async () => {
    await cluster.start();
    srcUrl = await cluster.createDatabase(SRC);
    tgtUrl = await cluster.createDatabase(TGT);
    const s = await connect(srcUrl);
    await s.query(schema);
    await s.query(`insert into public.t (v) select 'x' from generate_series(1, 1234); insert into private.ident default values; insert into private.ident default values;`);
    await s.end();
    const t = await connect(tgtUrl);
    await t.query(schema.replace('create sequence public.only_source;', 'create sequence public.only_target;'));
    // Replicated rows arrive with explicit ids, so the target sequence stays at its start.
    await t.query(`insert into public.t (id, v) select g, 'x' from generate_series(1, 1234) g`);
    await t.end();
  }, 120_000);

  afterAll(async () => {
    await cluster.dropDatabase(SRC).catch(() => {});
    await cluster.dropDatabase(TGT).catch(() => {});
    await cluster.stop();
  }, 60_000);

  const runScript = (args) =>
    spawnSync(process.execPath, [script, ...args], { encoding: 'utf8', env: { ...process.env, SOURCE_DATABASE_URL: srcUrl, TARGET_DATABASE_URL: tgtUrl } });

  const targetValues = async () => {
    const t = await connect(tgtUrl);
    const { rows } = await t.query(`select schemaname || '.' || sequencename as k, last_value::text as v from pg_sequences order by 1`);
    await t.end();
    return Object.fromEntries(rows.map((r) => [r.k, r.v]));
  };

  it('dry run (default) changes nothing and reports the missing sequence', async () => {
    const before = await targetValues();
    const r = runScript(['--margin', '100', '--json']);
    expect(r.status).toBe(1); // only_source is missing on the target
    const out = JSON.parse(r.stdout);
    expect(out.mode).toBe('dry-run');
    expect(out.applied).toBe(0);
    const by = Object.fromEntries(out.plan.map((p) => [p.key, p]));
    expect(by['public.t_id_seq']).toMatchObject({ action: 'set', desired: '1334' });
    expect(by['private.ident_id_seq']).toMatchObject({ action: 'set', desired: '102' });
    expect(by['public.unused_seq'].action).toBe('skip-unused');
    expect(by['public.only_source'].action).toBe('missing');
    expect(by['public.only_target'].action).toBe('extra');
    expect(await targetValues()).toEqual(before);
  });

  it('--apply sets the target, nextval continues past the margin, and a re-run is a no-op', async () => {
    const r = runScript(['--margin', '100', '--apply']);
    expect(r.status).toBe(1); // still reports the missing sequence
    expect(r.stdout).toMatch(/set 2;/);
    const values = await targetValues();
    expect(values['public.t_id_seq']).toBe('1334');
    expect(values['private.ident_id_seq']).toBe('102');
    expect(values['public.unused_seq']).toBeNull(); // last_value stays NULL

    const t = await connect(tgtUrl);
    const { rows } = await t.query(`insert into public.t (v) values ('after') returning id`);
    expect(rows[0].id).toBe('1335');
    await t.end();

    const again = runScript(['--margin', '100', '--apply', '--json']);
    const out = JSON.parse(again.stdout);
    expect(out.applied).toBe(0);
    expect(out.plan.find((p) => p.key === 'public.t_id_seq').action).toBe('skip-ahead');
  });

  it('the source connection is read-only even with --apply (swapping URLs cannot write to the source)', async () => {
    const s = await connect(srcUrl, { readOnly: true });
    await expect(s.query(`select setval('public.t_id_seq', 1)`)).rejects.toMatchObject({ code: '25006' });
    await s.end();
  });
});
