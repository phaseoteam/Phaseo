-- Surface Tev's model-card links and enable its choice-only Decisions route.
-- The Tev model and Together route are managed catalogue rows, so these
-- inserts are conditional and leave unrelated Together models untouched.

insert into public.v2_model_links (model_slug, link_kind, title, url, metadata)
select
  model.model_slug,
  link.link_kind,
  link.title,
  link.url,
  jsonb_build_object('source', 'together', 'model_card', 'https://huggingface.co/togethercomputer/Tev1-4B-experimental')
from public.v2_models as model
cross join (
  values
    (
      'weights',
      'Hugging Face weights',
      'https://huggingface.co/togethercomputer/Tev1-4B-experimental/tree/main'
    ),
    (
      'license',
      'Hugging Face license information',
      'https://huggingface.co/togethercomputer/Tev1-4B-experimental#license'
    )
) as link(link_kind, title, url)
where model.model_slug = 'together/tev1-4b-experimental'
on conflict (model_slug, link_kind, url) do update set
  title = excluded.title,
  metadata = public.v2_model_links.metadata || excluded.metadata,
  updated_at = now();

update public.v2_models
set license_url = 'https://huggingface.co/togethercomputer/Tev1-4B-experimental#license',
    metadata = metadata || jsonb_build_object('open_weights', true),
    updated_at = now()
where model_slug = 'together/tev1-4b-experimental';

insert into public.v2_route_capabilities (
  provider_model_id,
  capability_id,
  status,
  max_input_tokens,
  max_output_tokens,
  params,
  metadata
)
select
  route.provider_model_id,
  'decisions.make',
  'active',
  32768,
  8,
  jsonb_build_object('model', true, 'state', true, 'questions', true),
  jsonb_build_object(
    'source', 'together',
    'capability_evidence', jsonb_build_object(
      'status', 'documented',
      'source_url', 'https://api.together.ai/models/together/Tev1-4B-experimental',
      'question_types', jsonb_build_array('choice'),
      'min_options', 2,
      'max_options', 24,
      'response_format', 'single_option_label'
    )
  )
from public.v2_model_provider_routes as route
where route.provider_model_id = 'together:together/tev1-4b-experimental'
  and route.provider_slug = 'together'
  and route.model_slug = 'together/tev1-4b-experimental'
on conflict (provider_model_id, capability_id) do update set
  status = excluded.status,
  max_input_tokens = excluded.max_input_tokens,
  max_output_tokens = excluded.max_output_tokens,
  params = excluded.params,
  metadata = public.v2_route_capabilities.metadata || excluded.metadata,
  updated_at = now();

