insert into public.v2_pricing_sku_meters (
  sku_id,
  meter_key,
  modality,
  direction,
  unit,
  unit_quantity,
  price_nanos,
  display_label,
  display_unit,
  billable,
  meter_order,
  metadata
)
select
  sku.sku_id,
  meter.meter_key,
  meter.modality,
  meter.direction,
  meter.unit,
  meter.unit_quantity,
  meter.price_nanos,
  meter.display_label,
  meter.display_unit,
  meter.billable,
  meter.meter_order,
  meter.metadata
from public.v2_pricing_skus as sku
cross join (
  values
    (
      'input_tokens', 'text', 'input', 'token', 1000000::numeric,
      42000000::numeric, 'Input tokens', '1M tokens', true, 100,
      jsonb_build_object('source', 'together', 'price_per_million_usd', 0.042)
    ),
    (
      'output_tokens', 'text', 'output', 'token', 1000000::numeric,
      0::numeric, 'Output tokens', '1M tokens', true, 110,
      jsonb_build_object('source', 'together', 'price_per_million_usd', 0)
    )
) as meter(
  meter_key,
  modality,
  direction,
  unit,
  unit_quantity,
  price_nanos,
  display_label,
  display_unit,
  billable,
  meter_order,
  metadata
)
where sku.provider_model_id = 'together:together/tev1-4b-experimental'
  and sku.sku_code = 'together-tev1-decisions'
  and sku.version = 1
on conflict (sku_id, meter_key) do update set
  modality = excluded.modality,
  direction = excluded.direction,
  unit = excluded.unit,
  unit_quantity = excluded.unit_quantity,
  price_nanos = excluded.price_nanos,
  display_label = excluded.display_label,
  display_unit = excluded.display_unit,
  billable = excluded.billable,
  meter_order = excluded.meter_order,
  metadata = public.v2_pricing_sku_meters.metadata || excluded.metadata,
  updated_at = now();
