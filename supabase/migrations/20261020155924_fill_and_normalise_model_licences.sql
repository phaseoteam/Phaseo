where model.model_slug = corrections.model_slug
  and model.license = corrections.old_license;

update public.v2_models model
set license = base.license,
  license_url = coalesce(model.license_url, base.license_url)
from public.v2_models base
where model.variant_kind = 'free'
  and nullif(btrim(model.license), '') is null
  and base.model_slug = coalesce(model.base_model_slug, regexp_replace(model.model_slug, ':free$', ''))
  and nullif(btrim(base.license), '') is not null;
